# get positive definite covariance matrix from parameters
# This is tricky because for Zygote to work, no array modifications can be used.
function lower_triangular(dim , par)
	return [if(r >= c) 
				if (r == c)
					exp(par[div((r - 1) * r , 2) + c])
				else
					par[div((r - 1) * r , 2) + c]
				end
			else
				0.0
			end
				for r in 1:dim , c in 1:dim]
end

# get covariance matrix from parameters
function sigma_from_parameters(dim , par)
	if dim == 2
		l = [ exp(par[1]) 0.          ;
			  par[2]      exp(par[3]) ]
	elseif dim == 3
		l = [ exp(par[1]) 0.          0.          ;
			  par[2]      exp(par[3]) 0.          ;
			  par[4]      par[5]      exp(par[6]) ]
	elseif dim == 4
		l = [ exp(par[1]) 0.          0.          0.           ;
			  par[2]      exp(par[3]) 0.          0.           ;
			  par[4]      par[5]      exp(par[6]) 0.           ;
			  par[7]      par[8]      par[9]      exp(par[10]) ]
	else
		# TODO this is slow
		l = lower_triangular(dim , par)
	end
	return l * transpose(l)
end

# potential energy function for Hamiltonian Monte Carlo
function u(parameters , vec)
	sigma = sigma_from_parameters(2 , parameters)
	dist = MvNormal(sigma)
	return -logpdf(dist , vec)
end

# gradient of the potential energy function for Hamiltonian Monte Carlo
function nablau(parameters, vector)
	# ALTERNATIVE TO ZYGOTE NABLAU GENERATED BY:
	#    GOOGLE GEMINI
	# WAY FASTER THEN THE ZYGOTE VERSION
	dparameters = zero(parameters)
   
	autodiff(
	   Reverse,
	   u,
	   #Const(sp),                       # Non-differentiated argument
	   Duplicated(parameters, dparameters), # Argument to differentiate wrt
	   Const(vector)                    # Non-differentiated argument
	)
   
   return (dparameters,)
end


